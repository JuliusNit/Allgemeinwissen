/** Lorbeerkranz, oben offen */
function laurel(): Stroke[] {
  const s: Stroke[] = []
  const r = 8.6
  for (const side of [-1, 1]) {
    const a0 = side < 0 ? 105 : 75
    const a1 = side < 0 ? 250 : -70
    s.push(arc(12, 12.5, r, a0, a1, 0.75))
    for (let i = 1; i <= 5; i++) {
      const a = rad(a0 + ((a1 - a0) * i) / 5.4)
      const px = 12 + Math.cos(a) * r
      const py = 12.5 + Math.sin(a) * r
      const dir = (Math.atan2(Math.cos(a) * Math.sign(a1 - a0), -Math.sin(a) * Math.sign(a1 - a0)) * 180) / Math.PI
      for (const k of [-1, 1]) {
        const rot = dir + k * 40 * -side
        s.push(ellipse(px + Math.cos(rad(rot)) * 2.1, py + Math.sin(rad(rot)) * 2.1, 2.3, 0.95, rot, 0.6))
      }
    }
  }
  return s
}

/** Ammonit: logarithmische Spirale mit Rippen */
function ammonite(): Stroke[] {
  const k = 0.165
  const r = (t: number) => 9.6 * Math.exp(-k * t)
  const T = 2.4 * 2 * Math.PI
  const s: Stroke[] = [curve((u) => at(12, 12, r(u * T), (u * T * 180) / Math.PI), 180)]
  for (let t = 0.35; t < 2 * Math.PI; t += 0.52) s.push(line(at(12, 12, r(t), (t * 180) / Math.PI), at(12, 12, r(t + 2 * Math.PI), (t * 180) / Math.PI), 0.6))
  return s
}

/** Geschlossene, glatte Kurve durch die Punkte (Catmull-Rom) */
function smooth(pts: Pt[], w?: number): Stroke {
  const n = pts.length
  const out: Pt[] = []
  for (let i = 0; i < n; i++) {
    const [p0, p1, p2, p3] = [pts[(i - 1 + n) % n], pts[i], pts[(i + 1) % n], pts[(i + 2) % n]]
    for (let k = 0; k < 12; k++) {
      const t = k / 12
      const c = (j: 0 | 1) => 0.5 * (2 * p1[j] + (p2[j] - p0[j]) * t + (2 * p0[j] - 5 * p1[j] + 4 * p2[j] - p3[j]) * t * t + (3 * p1[j] - p0[j] - 3 * p2[j] + p3[j]) * t * t * t)
      out.push([c(0), c(1)])
    }
  }
  return { pts: out, closed: true, w }
}

/** Fussabdruck, Ferse bei (x, y), um rot gedreht; side -1 = linker Fuss */
function foot(x: number, y: number, rot: number, side: 1 | -1): Stroke[] {
  const p = (dx: number, dy: number): Pt => [x + dx * side, y + dy]
  const sole = smooth([p(-1.7, 0), p(0, 1.8), p(1.7, 0), p(1.4, -3.2), p(2.5, -7), p(0.6, -9.4), p(-2.1, -8.3), p(-1.5, -3.6)])
  const toes = [[-2.1, -10.9, 1.8], [-0.7, -11.7, 1.5], [0.7, -11.7, 1.4], [1.9, -11.1, 1.3], [2.8, -10, 1.2]].map(([dx, dy, w]) => dot(...p(dx, dy), w))
  return turn([sole, ...toes], rot * side, [x, y])
}

/** Gleis als Linie mit Schwellen */
function track(s: Stroke, gap = 3.2, half = 1.7): Stroke[] {
  const out: Stroke[] = [s]
  let acc = gap / 2
  for (let i = 1; i < s.pts.length; i++) {
    const [x0, y0] = s.pts[i - 1]
    const [x1, y1] = s.pts[i]
    const d = Math.hypot(x1 - x0, y1 - y0) || 1
    acc += d
    if (acc < gap) continue
    acc = 0
    const nx = (-(y1 - y0) / d) * half
    const ny = ((x1 - x0) / d) * half
    out.push(line([x1 + nx, y1 + ny], [x1 - nx, y1 - ny], 0.7))
  }
  return out
}

