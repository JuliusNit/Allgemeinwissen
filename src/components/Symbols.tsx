const rad = (d: number) => (d * Math.PI) / 180
const at = (cx: number, cy: number, r: number, deg: number): Pt => [cx + Math.cos(rad(deg)) * r, cy + Math.sin(rad(deg)) * r]
const dot = (x: number, y: number, w = 2.4) => line([x - 0.1, y], [x + 0.1, y], w)
const mirror = (s: Stroke[]): Stroke[] => s.map((st) => ({ ...st, pts: st.pts.map(([x, y]): Pt => [24 - x, y]) }))

/** Striche um einen Punkt drehen (Grad, im Uhrzeigersinn) */
function turn(strokes: Stroke[], deg: number, c: Pt = [12, 12]): Stroke[] {
  const cs = Math.cos(rad(deg))
  const sn = Math.sin(rad(deg))
  return strokes.map((s) => ({ ...s, pts: s.pts.map(([x, y]): Pt => [c[0] + (x - c[0]) * cs - (y - c[1]) * sn, c[1] + (x - c[0]) * sn + (y - c[1]) * cs]) }))
}

function star(cx: number, cy: number, r: number, ri: number, n = 5, w?: number): Stroke[] {
  const pts: Pt[] = []
  for (let k = 0; k < 2 * n; k++) pts.push(at(cx, cy, k % 2 ? ri : r, -90 + (k * 180) / n))
  return poly(pts, true, w)
}

function rays(cx: number, cy: number, r0: number, r1: number, n: number, w?: number, off = 0): Stroke[] {
  return Array.from({ length: n }, (_, k) => line(at(cx, cy, r0, off + (k * 360) / n), at(cx, cy, r1, off + (k * 360) / n), w))
}

/** Knoten (Kreise) mit Verbindungen, die am Kreisrand enden */
function graph(nodes: Pt[], r: number, edges: [number, number][]): Stroke[] {
  const s = nodes.map(([x, y]) => circle(x, y, r))
  for (const [a, b] of edges) {
    const [x0, y0] = nodes[a]
    const [x1, y1] = nodes[b]
    const d = Math.hypot(x1 - x0, y1 - y0)
    const ux = (x1 - x0) / d
    const uy = (y1 - y0) / d
    s.push(line([x0 + ux * (r + 0.9), y0 + uy * (r + 0.9)], [x1 - ux * (r + 0.9), y1 - uy * (r + 0.9)], 0.8))
  }
  return s
}

