/** Lipid-Doppelschicht; ohne die Koepfe in `gap` (Durchgang) */
function bilayer(gap: number[] = []): Stroke[] {
  const s: Stroke[] = []
  for (let k = 0; k < 6; k++) {
    if (gap.includes(k)) continue
    const x = 3.5 + 3.4 * k
    s.push(circle(x, 6.5, 1.25), line([x, 7.9], [x, 11], 0.7), circle(x, 17.5, 1.25), line([x, 16.1], [x, 13], 0.7))
  }
  return s
}

